CREATE TABLE IF NOT EXISTS ai_automation_task_drafts (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    project_id BIGINT NOT NULL,
    name VARCHAR(128) NOT NULL,
    task_type VARCHAR(32) NOT NULL,
    automation_type VARCHAR(16) NOT NULL,
    repository_url VARCHAR(500) NOT NULL,
    branch VARCHAR(128) NOT NULL,
    framework VARCHAR(64) NOT NULL,
    test_path VARCHAR(255),
    execute_command VARCHAR(1000),
    environment VARCHAR(32) NOT NULL,
    parameters_json TEXT,
    pipeline_type VARCHAR(32),
    allure_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    jenkins_job VARCHAR(255),
    missing_items_json TEXT,
    risk_hints_json TEXT,
    status VARCHAR(16) NOT NULL,
    model_name VARCHAR(128),
    provider VARCHAR(64),
    prompt_name VARCHAR(128),
    prompt_version VARCHAR(32),
    created_by BIGINT NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL
);
